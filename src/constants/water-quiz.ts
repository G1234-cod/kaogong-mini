/** 随机抽一道喝水题，避开上一杯抽过的（storage 记忆，防连续重复） */
export function pickWaterQuiz(): WaterQuiz {
  const last = Number(Taro.getStorageSync('last_water_quiz_id') ?? -1)
  const pool = WATER_QUIZ.filter((q) => q.id !== last)
  const q = pool[Math.floor(Math.random() * pool.length)] ?? WATER_QUIZ[0]
  Taro.setStorageSync('last_water_quiz_id', String(q.id))
  return q
}
